#!/usr/bin/env node
// Check the declarations of Lean modules in proof/ (tools/modts.mjs output) with tsc.
//
//   node tools/modcheck.mjs PROOF_DIR MODULE... [--limit N] [--no-run]
//
// For each MODULE, writes PROOF_DIR/check/<Module path>.check.ts and runs tools/tsc.sh on it:
//  - the environment is the module's own Decls (each tagged with its position, Idx) plus
//    the Decls of every module it transitively references (manifest `uses`), flattened;
//  - each declaration D_i is checked with CheckDeclAt<Env, D_i, i>: it sees every imported
//    declaration and only the earlier declarations of its own module. Imported modules are
//    checked by their own check files; Lean's module imports are acyclic.
// Declaration order within a module is the export order (dependencies first).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname, relative, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";

const args = process.argv.slice(2);
const flag = (f) => { const i = args.indexOf(f); return i >= 0 ? args.splice(i, 1).length > 0 : false; };
const li = args.indexOf("--limit");
const LIMIT = li >= 0 ? Number(args.splice(li, 2)[1]) : Infinity;
const noRun = flag("--no-run");
const oi = args.indexOf("--only");
const ONLY = oi >= 0 ? Number(args.splice(oi, 2)[1]) : null; // check just declaration #ONLY
const [proofArg, ...mods] = args;
const PROOF = resolve(proofArg);
const REPO = resolve(new URL("..", import.meta.url).pathname);
const manifest = JSON.parse(readFileSync(join(PROOF, "manifest.json"), "utf8")).modules;
const modPath = (m) => m.split(".").join("/");
const alias = (m) => "M" + createHash("sha1").update(m).digest("hex").slice(0, 12);

for (const mod of mods) {
  const info = manifest[mod];
  if (!info) throw new Error(`unknown module ${mod}`);
  // Transitive module closure.
  const closure = new Set(), stack = [...info.uses];
  while (stack.length) { const m = stack.pop(); if (closure.has(m)) continue; closure.add(m); stack.push(...manifest[m].uses); }
  const file = join(PROOF, "check", modPath(mod) + (ONLY === null ? "" : `.only${ONLY}`) + ".check.ts");
  mkdirSync(dirname(file), { recursive: true });
  const rel = (m) => { let r = relative(dirname(file), join(PROOF, "ts", modPath(m) + ".ts")).replace(/\.ts$/, ""); return r.startsWith(".") ? r : "./" + r; };
  let kernel = relative(dirname(file), join(REPO, "src/index")); if (!kernel.startsWith(".")) kernel = "./" + kernel;
  const decls = info.decls.slice(0, LIMIT);
  const lines = [`// Generated by tools/modcheck.mjs: check ${decls.length} declarations of ${mod}. Do not edit.`,
    `import type { CheckDeclAt, Verified, Idx, Flat } from "${kernel}";`,
    `import type { Decls as Own } from "${rel(mod)}";`];
  const imp = [...closure].sort();
  // Imported modules through their interfaces (theorems as statements only): their proofs
  // are checked by their own check files.
  for (const m of imp) lines.push(`import type { Decls as ${alias(m)} } from "${rel(m)}.api";`);
  lines.push(`type Imported = Flat<{}${imp.map((m) => ` & ${alias(m)}`).join("")}>;`);
  lines.push("type OwnIdx = {");
  info.decls.forEach((n, i) => lines.push(`  ${JSON.stringify(n)}: Idx<Own[${JSON.stringify(n)}], ${i}>;`));
  lines.push("};", "type Env = Imported & OwnIdx;", "");
  decls.forEach((n, i) => { if (ONLY === null || i === ONLY) lines.push(`export type C${i} = Verified<CheckDeclAt<Env, Own[${JSON.stringify(n)}], ${i}>>;`); });
  writeFileSync(file, lines.join("\n") + "\n");
  const tsconfig = join(dirname(file), "tsconfig." + mod + (ONLY === null ? "" : `.only${ONLY}`) + ".json");
  writeFileSync(tsconfig, JSON.stringify({ compilerOptions: { strict: true, noEmit: true, skipLibCheck: true, types: [],
    moduleResolution: "bundler", module: "esnext", target: "esnext" }, files: ["./" + file.split("/").pop()] }));
  console.log(`${mod}: ${decls.length}/${info.decls.length} declarations, ${imp.length} imported modules`);
  if (noRun) continue;
  const t = Date.now();
  const r = spawnSync(join(REPO, "tools/tsc.sh"), ["-p", tsconfig], { encoding: "utf8", env: { ...process.env, TSC_HEAP_MB: process.env.TSC_HEAP_MB ?? "16000" } });
  const errs = (r.stdout + r.stderr).split("\n").filter((l) => l.includes("error"));
  console.log(`  tsc: ${r.status === 0 ? "OK, all verified" : `FAILED (${errs.length} errors)`} in ${((Date.now() - t) / 1000).toFixed(1)}s`);
  for (const e of errs.slice(0, 5)) console.log("   ", e.replace(/^.*error TS\d+: /, "").slice(0, 220));
}
