#!/usr/bin/env node
// Split a lean4export NDJSON export into a chain of TypeScript projects (project
// references), checked by ONE `tsc -b` call with per-project caching.
//
//   node tools/lean2ts-split.mjs IN.ndjson OUTDIR [--chunk N] [--thm-as-axiom]
//   tools/tsc.sh -b OUTDIR
//
// Chunk k holds N consecutive declarations (export order is dependency order) and the
// DAG nodes first introduced with them. It exports those nodes and
//   Env = (Env of chunk k-1) & { this chunk's declarations }
// and checks each of its declarations against everything before it. Downstream chunks
// see only upstream .d.ts files, so no project re-checks another's declarations.
//
// --thm-as-axiom: theorems enter Env as axioms with the same statement (proof
// irrelevance at module boundaries; sound, see AsAxiom in src/decl.ts).

import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { convert } from "./lean2ts.mjs";

const args = process.argv.slice(2);
const flag = (f) => { const i = args.indexOf(f); return i >= 0 ? args.splice(i, 1) : null; };
const thmAsAxiom = !!flag("--thm-as-axiom");
const ci = args.indexOf("--chunk");
const CHUNK = ci >= 0 ? Number(args.splice(ci, 2)[1]) : 25;
const [inPath, outDir] = args;
if (!inPath || !outDir) { console.error("usage: lean2ts-split.mjs IN.ndjson OUTDIR [--chunk N] [--thm-as-axiom]"); process.exit(2); }

const { items } = convert(readFileSync(inPath, "utf8"), inPath);

// Group: aliases are attached to the chunk of the next declaration.
const chunks = [];
let cur = { aliases: [], decls: [] };
for (const it of items) {
  if (it.alias) cur.aliases.push(it);
  else { cur.decls.push(it); if (cur.decls.length === CHUNK) { chunks.push(cur); cur = { aliases: [], decls: [] }; } }
}
if (cur.decls.length || cur.aliases.length) chunks.push(cur);

const owner = new Map(); // alias -> chunk index
chunks.forEach((c, k) => c.aliases.forEach((a) => owner.set(a.alias, k)));

rmSync(outDir, { recursive: true, force: true });
const kernel = resolve("src");
const KERNEL = "LZero, LSucc, LMax, LIMax, LParam, B, Sort, Const, App, Lam, Pi, Let, Proj, NatLit, StrLit, " +
  "Axiom, Defn, Thm, Opaque, QuotDecl, Induct, Ctor, Rec, RecRule, CheckDecl, Verified, AsAxiom";
const refs = (s) => s.match(/\b[EU]\d+\b/g) ?? [];
let declNo = 0;

chunks.forEach((c, k) => {
  const dir = join(outDir, `c${k}`);
  mkdirSync(dir, { recursive: true });
  const own = new Set(c.aliases.map((a) => a.alias));
  const imports = new Map(); // chunk -> Set(alias)
  for (const s of [...c.aliases.map((a) => a.rhs), ...c.decls.map((d) => d.decl)])
    for (const r of refs(s)) if (!own.has(r)) {
      const j = owner.get(r);
      if (j === undefined) throw new Error(`unknown node ${r}`);
      if (!imports.has(j)) imports.set(j, new Set());
      imports.get(j).add(r);
    }
  if (k > 0 && !imports.has(k - 1)) imports.set(k - 1, new Set());
  const kr = relative(dir, kernel).replaceAll("\\", "/");
  const lines = [`// Generated by tools/lean2ts-split.mjs (chunk ${k} of ${chunks.length}). Do not edit.`,
    `import type { ${KERNEL} } from "${kr}/index";`];
  for (const [j, names] of [...imports].sort((a, b) => a[0] - b[0])) {
    const ns = [...names].sort();
    if (j === k - 1) ns.push("Env as Prev");
    lines.push(`import type { ${ns.join(", ")} } from "../c${j}/index";`);
  }
  lines.push("", ...c.aliases.map((a) => `export type ${a.alias} = ${a.rhs};`), "");
  const envParts = [];
  c.decls.forEach((d) => {
    const id = `D${declNo++}`;
    const before = [k > 0 ? "Prev" : "{}", ...envParts].join(" & ");
    lines.push(`export type ${id} = ${d.decl};`);
    lines.push(`export type Check_${id} = Verified<CheckDecl<${before}, ${id}>>; // ${d.name}`);
    envParts.push(`{ ${d.name}: ${thmAsAxiom ? `AsAxiom<${id}>` : id} }`);
  });
  lines.push("", `export type Env = ${[k > 0 ? "Prev" : "{}", ...envParts].join(" & ")};`, "");
  writeFileSync(join(dir, "index.ts"), lines.join("\n"));
  writeFileSync(join(dir, "tsconfig.json"), JSON.stringify({
    compilerOptions: {
      composite: true, declaration: true, emitDeclarationOnly: true, outDir: "out", rootDir: ".",
      strict: true, target: "esnext", module: "esnext", moduleResolution: "bundler", skipLibCheck: true, types: [],
    },
    files: ["index.ts"],
    references: [{ path: relative(dir, kernel) }, ...[...imports.keys()].sort((a, b) => a - b).map((j) => ({ path: `../c${j}` }))],
  }, null, 2));
});
writeFileSync(join(outDir, "tsconfig.json"), JSON.stringify(
  { files: [], references: chunks.map((_, k) => ({ path: `c${k}` })) }, null, 2));
console.error(`${outDir}: ${declNo} declarations in ${chunks.length} projects of ${CHUNK}${thmAsAxiom ? ", theorems exported as axioms" : ""}`);
